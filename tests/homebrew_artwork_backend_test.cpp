void DecodesPngAndJpegToRgba() {
  const auto png = DecodeArtwork(SmallPng());
  assert(png && png->width == 2 && png->height == 1 && png->rgba.size() == 8);
  assert(png->rgba[0] > 200 && png->rgba[1] < 30 && png->rgba[4] < 30 && png->rgba[5] > 200);

  const auto jpeg = DecodeArtwork(SmallJpeg());
  assert(jpeg && jpeg->width == 2 && jpeg->height == 1 && jpeg->rgba.size() == 8);
  assert(jpeg->rgba[3] == 255 && jpeg->rgba[7] == 255);
}

void DecodeAllocatorRejectsBudgetExhaustion() {
  assert(!artwork_internal::DecodeArtworkWithAllocationBudget(SmallPng(), 1));
  assert(artwork_internal::DecodeArtworkWithAllocationBudget(
      SmallPng(), kMaxArtworkDecodeAllocationBytes));
}

void RejectsEmptyCorruptAndTransferOverflow() {
  assert(!DecodeArtwork({}));
  assert(!DecodeArtwork({1, 2, 3, 4}));
  assert(!DecodeArtwork(std::vector<std::uint8_t>(kMaxArtworkTransferBytes + 1, 0)));
}

