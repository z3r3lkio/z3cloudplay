int main(int argc, char** argv) {
  if (argc == 3 && std::string(argv[1]) == "--live-smoke") {
    HttpArtworkBackend backend(argv[2]);
    std::atomic<bool> cancel{false};
    const auto image = backend.Load(
        {1, 440,
         "https://cdn.cloudflare.steamstatic.com/steam/apps/440/library_600x900.jpg"},
        cancel);
    assert(image && !image->rgba.empty());
    std::printf("artwork %ux%u %zu bytes\n", image->width, image->height,
                image->rgba.size());
    return 0;
  }
  assert(argc == 1);
  DecodesPngAndJpegToRgba();
  DecodeAllocatorRejectsBudgetExhaustion();
  RejectsEmptyCorruptAndTransferOverflow();
  RejectsOversizedPngDimensionsBeforePixelAllocation();
  InvalidHttpIdentityIsRejectedWithoutTransport();
}
