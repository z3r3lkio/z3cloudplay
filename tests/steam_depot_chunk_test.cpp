std::array<std::uint8_t, 32> Key() {
  std::array<std::uint8_t, 32> key{};
  std::memcpy(key.data(), kKey, sizeof(kKey));
  return key;
}

std::array<std::uint8_t, 20> Sha() {
  std::array<std::uint8_t, 20> sha{};
  std::memcpy(sha.data(), kSha1, sizeof(kSha1));
  return sha;
}

std::string PlainText() {
  std::string text;
  for (int i = 0; i < 40; ++i) {
    char line[96];
    std::snprintf(line, sizeof(line), "Z3CloudPlay depot chunk line %03d: the quick brown fox jumps over the lazy dog\n", i);
    text += line;
  }
  return text;
}

template <std::size_t N>
Bytes V(const std::uint8_t (&a)[N]) {
  return Bytes(a, a + N);
}

bool IsPlain(const Bytes& out) {
  const std::string text = PlainText();
  return out.size() == text.size() && std::memcmp(out.data(), text.data(), text.size()) == 0;
}

void TestRoundTrip(const Bytes& enc) {
  Bytes out;
  CHECK(ProcessDepotChunk(enc, Key(), kPlainSize, kAdler0, Sha(), &out) == ChunkError::kNone);
  CHECK(IsPlain(out));
  // Zero manifest crc falls back to the chunk SHA-1.
  CHECK(ProcessDepotChunk(enc, Key(), kPlainSize, 0, Sha(), &out) == ChunkError::kNone);
  CHECK(IsPlain(out));
}

void TestFailures(const Bytes& enc) {
  Bytes out;
  // Wrong key: padding check or container magic fails (or, by chance, the checksum).
  std::array<std::uint8_t, 32> wrong = Key();
  wrong[0] ^= 0x55;
  const ChunkError wrong_key = ProcessDepotChunk(enc, wrong, kPlainSize, kAdler0, Sha(), &out);
  CHECK(wrong_key != ChunkError::kNone);
  CHECK(out.empty());

  CHECK(ProcessDepotChunk(enc, Key(), kPlainSize + 1, kAdler0, Sha(), &out) == ChunkError::kSize);
  CHECK(ProcessDepotChunk(enc, Key(), kPlainSize, kAdler0 ^ 1U, Sha(), &out) == ChunkError::kChecksum);
  std::array<std::uint8_t, 20> bad_sha = Sha();
  bad_sha[3] ^= 1;
  CHECK(ProcessDepotChunk(enc, Key(), kPlainSize, 0, bad_sha, &out) == ChunkError::kChecksum);

  // Tampering with any ciphertext byte must never produce accepted output.
  for (std::size_t i = 0; i < enc.size(); ++i) {
    Bytes t = enc;
    t[i] ^= 0x80;
    CHECK(ProcessDepotChunk(t, Key(), kPlainSize, kAdler0, Sha(), &out) != ChunkError::kNone);
  }

  // Truncation: not block aligned, and block aligned.
  Bytes cut(enc.begin(), enc.end() - 1);
  CHECK(ProcessDepotChunk(cut, Key(), kPlainSize, kAdler0, Sha(), &out) == ChunkError::kDecrypt);
  Bytes cut_block(enc.begin(), enc.end() - 16);
  CHECK(ProcessDepotChunk(cut_block, Key(), kPlainSize, kAdler0, Sha(), &out) != ChunkError::kNone);
  CHECK(ProcessDepotChunk(Bytes(), Key(), kPlainSize, kAdler0, Sha(), &out) == ChunkError::kDecrypt);
  CHECK(ProcessDepotChunk(Bytes(enc.begin(), enc.begin() + 16), Key(), kPlainSize, kAdler0, Sha(), &out) ==
        ChunkError::kDecrypt);
}

void TestDecode() {
  Bytes out;
  const Bytes vz = V(kVzPlain), vsz = V(kVszPlain), pk = V(kPkDeflatePlain);
  CHECK(DecodeDepotChunk(vz.data(), vz.size(), &out) == ChunkError::kNone && IsPlain(out));
  CHECK(DecodeDepotChunk(vsz.data(), vsz.size(), &out) == ChunkError::kNone && IsPlain(out));
  CHECK(DecodeDepotChunk(pk.data(), pk.size(), &out) == ChunkError::kNone && IsPlain(out));

  // Bad magic.
  for (const Bytes* src : {&vz, &vsz, &pk}) {
    Bytes bad = *src;
    bad[1] = 'X';
    CHECK(DecodeDepotChunk(bad.data(), bad.size(), &out) == ChunkError::kFormat);
  }
  Bytes footer = vz;
  footer.back() = 'x';
  CHECK(DecodeDepotChunk(footer.data(), footer.size(), &out) == ChunkError::kFormat);
  footer = vsz;
  footer.back() = 'x';
  CHECK(DecodeDepotChunk(footer.data(), footer.size(), &out) == ChunkError::kFormat);
  const std::uint8_t unknown[] = {'Z', 'Z', 'Z', 'Z', 0, 0, 0, 0};
  CHECK(DecodeDepotChunk(unknown, sizeof(unknown), &out) == ChunkError::kFormat);
  CHECK(DecodeDepotChunk(unknown, 0, &out) == ChunkError::kFormat);

  // Truncation at every length must fail cleanly (never crash, never succeed).
  for (const Bytes* src : {&vz, &vsz, &pk}) {
    for (std::size_t n = 0; n < src->size(); ++n) {
      CHECK(DecodeDepotChunk(src->data(), n, &out) != ChunkError::kNone);
    }
  }

  // Implausible declared sizes are rejected before allocating.
  Bytes huge = vsz;
  huge[huge.size() - 7] = 0x7f;  // size = 0x7f......
  CHECK(DecodeDepotChunk(huge.data(), huge.size(), &out) == ChunkError::kSize);
  huge = vz;
  huge[huge.size() - 3] = 0x7f;
  CHECK(DecodeDepotChunk(huge.data(), huge.size(), &out) == ChunkError::kSize);

  // Corrupt compressed payloads are errors, not crashes.
  Bytes corrupt = vz;
  for (std::size_t i = 14; i < corrupt.size() - 10; i += 3) corrupt[i] ^= 0xA5;
  CHECK(DecodeDepotChunk(corrupt.data(), corrupt.size(), &out) != ChunkError::kNone || !IsPlain(out));
  corrupt = vsz;
  for (std::size_t i = 10; i < corrupt.size() - 15; i += 3) corrupt[i] ^= 0xA5;
  CHECK(DecodeDepotChunk(corrupt.data(), corrupt.size(), &out) != ChunkError::kNone);
}

void TestAdler() {
  const std::uint8_t abc[] = {'a', 'b', 'c'};
  // Zero-seeded variant: a = 294, b = 97 + 195 + 294 = 586 (zlib's seed-1 Adler-32 would be 0x024d0127).
  CHECK(DepotChunkAdler32(abc, 3) == 0x024a0126U);
  CHECK(DepotChunkAdler32(abc, 0) == 0);
  const std::string text = PlainText();
  CHECK(DepotChunkAdler32(reinterpret_cast<const std::uint8_t*>(text.data()), text.size()) == kAdler0);
}

void TestSymmetricDecrypt() {
  Bytes out;
  const std::array<std::uint8_t, 32> key = Key();
  const Bytes enc = V(kEncVz);
  CHECK(SymmetricDecrypt(enc.data(), enc.size(), key, &out));
  CHECK(out.size() == V(kVzPlain).size());
  CHECK(out == V(kVzPlain));
  CHECK(!SymmetricDecrypt(enc.data(), 16, key, &out));
  CHECK(!SymmetricDecrypt(enc.data(), 0, key, &out));
  CHECK(!SymmetricDecrypt(enc.data(), enc.size() - 1, key, &out));
  CHECK(!SymmetricDecrypt(nullptr, 32, key, &out));
  // Corrupting the last ciphertext block garbles the PKCS7 padding (almost surely invalid).
  Bytes t = enc;
  t[t.size() - 1] ^= 0xFF;
  CHECK(!SymmetricDecrypt(t.data(), t.size(), key, &out));
}

